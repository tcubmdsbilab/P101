-- 1. Drop old RPC functions first
DROP FUNCTION IF EXISTS public.p101_increment_counter(text, text, text);
DROP FUNCTION IF EXISTS public.p101_increment_counter(text, text, text, text);
DROP FUNCTION IF EXISTS public.p101_get_counters();

-- 2. Drop old tables with possibly inconsistent schemas
DROP TABLE IF EXISTS public."TblP101ViewEvents" CASCADE;
DROP TABLE IF EXISTS public."TblP101ViewCounters" CASCADE;
DROP TABLE IF EXISTS public."TblP101Events" CASCADE;
DROP TABLE IF EXISTS public."TblP101Counters" CASCADE;

-- 3. Create canonical counter table
CREATE TABLE public."TblP101Counters" (
  counter_key text PRIMARY KEY,
  project_code text NOT NULL DEFAULT 'P101',
  target_type text NOT NULL CHECK (target_type IN ('page', 'version')),
  version_code text,
  target_title text NOT NULL,
  target_url text,
  view_count bigint NOT NULL DEFAULT 0 CHECK (view_count >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- 4. Create canonical event log table
CREATE TABLE public."TblP101Events" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  counter_key text NOT NULL REFERENCES public."TblP101Counters"(counter_key) ON DELETE CASCADE,
  project_code text NOT NULL DEFAULT 'P101',
  target_type text NOT NULL CHECK (target_type IN ('page', 'version')),
  version_code text,
  referrer text,
  session_id text,
  user_agent text,
  clicked_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX "idx_TblP101Events_counter_key" ON public."TblP101Events"(counter_key);
CREATE INDEX "idx_TblP101Events_clicked_at" ON public."TblP101Events"(clicked_at DESC);

