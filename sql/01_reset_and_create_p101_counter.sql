-- 6. Create canonical RPC function used by assets/app.js
CREATE FUNCTION public.p101_increment_counter(
  p_counter_key text,
  p_referrer text DEFAULT NULL,
  p_session_id text DEFAULT NULL
)
RETURNS TABLE (
  counter_key text,
  view_count bigint
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_target_type text;
  v_version_code text;
  v_view_count bigint;
BEGIN
  -- Lock and update exactly one known counter.
  UPDATE public."TblP101Counters" AS c
  SET view_count = c.view_count + 1,
      updated_at = now()
  WHERE c.counter_key = p_counter_key
  RETURNING c.target_type, c.version_code, c.view_count
  INTO v_target_type, v_version_code, v_view_count;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Unknown P101 counter_key: %', p_counter_key
      USING ERRCODE = '22023';
  END IF;

  INSERT INTO public."TblP101Events"
    (counter_key, project_code, target_type, version_code, referrer, session_id, user_agent)
  VALUES
    (p_counter_key, 'P101', v_target_type, v_version_code, p_referrer, p_session_id, NULL);

  RETURN QUERY
  SELECT p_counter_key::text AS counter_key, v_view_count::bigint AS view_count;
END;
$$;

-- 7. Enable RLS
ALTER TABLE public."TblP101Counters" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."TblP101Events" ENABLE ROW LEVEL SECURITY;

-- 8. Public read policy for counters
CREATE POLICY "P101 counters are publicly readable"
ON public."TblP101Counters"
FOR SELECT
TO anon, authenticated
USING (true);

-- 9. Direct event insert policy is optional; RPC uses SECURITY DEFINER.
-- Keep direct table writing closed by not creating an INSERT policy.

-- 10. Grants
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON public."TblP101Counters" TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.p101_increment_counter(text, text, text) TO anon, authenticated;

-- 11. Refresh PostgREST schema cache
NOTIFY pgrst, 'reload schema';

